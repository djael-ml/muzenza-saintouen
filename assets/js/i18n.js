document.addEventListener('DOMContentLoaded', () => {
    let currentLang = localStorage.getItem('lang');
    
    if (!currentLang) {
        const browserLang = navigator.language.slice(0, 2).toLowerCase();
        if (browserLang === 'fr' || browserLang === 'pt') {
            currentLang = browserLang;
        } else {
            currentLang = 'en';
        }
        localStorage.setItem('lang', currentLang);
    }
    
    applyLanguage(currentLang);

    // Language switcher logic (Dropdown)
    const langDropdownBtn = document.getElementById('langDropdown');
    if (langDropdownBtn) {
        langDropdownBtn.innerText = currentLang.toUpperCase();
    }
    
    document.querySelectorAll('.lang-option').forEach(option => {
        option.addEventListener('click', (e) => {
            e.preventDefault();
            const selectedLang = e.target.getAttribute('data-lang');
            applyLanguage(selectedLang);
            localStorage.setItem('lang', selectedLang);
            if (langDropdownBtn) {
                langDropdownBtn.innerText = selectedLang.toUpperCase();
            }
        });
    });
});

function applyLanguage(lang) {
    const dict = translations[lang];
    if (!dict) return;

    document.documentElement.lang = lang;
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                el.innerHTML = dict[key];
            }
        }
    });

    // Update select options if they have data-i18n
    document.querySelectorAll('option[data-i18n]').forEach(opt => {
        const key = opt.getAttribute('data-i18n');
        if (dict[key]) {
            opt.innerText = dict[key];
        }
    });
}
